-- QA Shop — schema
-- Applied automatically by the API on first start (see app/src/schema.js).
--
-- Testers: read this file critically. It is a test basis like any other, and it is
-- not perfect. Week 7 asks you to find what it fails to protect against.

CREATE TABLE customers (
  id            integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name    text        NOT NULL,
  last_name     text        NOT NULL,
  email         text        NOT NULL UNIQUE,
  password_hash text        NOT NULL,
  country       char(2),
  is_active     boolean     NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE products (
  id          integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku         text          NOT NULL UNIQUE,
  name        text          NOT NULL,
  description text,
  category    text          NOT NULL,
  price       numeric(12,2) NOT NULL CHECK (price >= 0),
  stock       integer       NOT NULL DEFAULT 0,
  is_active   boolean       NOT NULL DEFAULT true,
  created_at  timestamptz   NOT NULL DEFAULT now()
);

CREATE INDEX products_category_idx ON products (category);

CREATE TABLE coupons (
  code             text          PRIMARY KEY,
  percent_off      integer       NOT NULL CHECK (percent_off BETWEEN 1 AND 100),
  min_order_amount numeric(12,2) NOT NULL DEFAULT 0,
  expires_at       timestamptz,
  is_active        boolean       NOT NULL DEFAULT true
);

CREATE TABLE orders (
  id           integer       GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
  customer_id  integer       NOT NULL REFERENCES customers (id),
  status       text          NOT NULL DEFAULT 'pending'
                             CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled')),
  subtotal     numeric(12,2) NOT NULL DEFAULT 0,
  discount     numeric(12,2) NOT NULL DEFAULT 0,
  total_amount numeric(12,2) NOT NULL DEFAULT 0,
  coupon_code  text          REFERENCES coupons (code),
  created_at   timestamptz   NOT NULL DEFAULT now(),
  updated_at   timestamptz   NOT NULL DEFAULT now()
);

CREATE INDEX orders_customer_id_idx ON orders (customer_id);

CREATE TABLE order_items (
  id          integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    integer       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  product_id  integer       NOT NULL REFERENCES products (id),
  qty         integer       NOT NULL,
  unit_price  numeric(12,2) NOT NULL,
  line_total  numeric(12,2) NOT NULL
);

CREATE INDEX order_items_order_id_idx ON order_items (order_id);
